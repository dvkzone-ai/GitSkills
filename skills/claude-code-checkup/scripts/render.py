    ap.add_argument("--data", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--lang", default="en")
    ap.add_argument("--strings")
    a = ap.parse_args()
    data = json.loads(Path(a.data).read_text(encoding="utf-8"))
